#!/usr/bin/env python3
"""mkicns.py - write the Mac OS X icon family ('icns' resource) for the
Carbon build, as a Rez source, from img/*.png.

Usage: mkicns.py OUT.r

Holds the 16, 32, 48 and 128 pixel icons in the formats Mac OS X 10.0 to
10.4 read: 24-bit RGB compressed per channel (is32, il32, ih32, it32) with
8-bit alpha masks (s8mk, l8mk, h8mk, t8mk). The Finder shows it for the
application in place of the 32-pixel ICN#/icl8 family of the same ID.
"""
import os
import struct
import sys

from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SIZES = [(16, b"is32", b"s8mk"), (32, b"il32", b"l8mk"), (48, b"ih32", b"h8mk"), (128, b"it32", b"t8mk")]


def rle(channel):
    """The icns RLE: a run of 3 to 130 equal bytes is 0x80 + (n - 3) and the
    byte; 1 to 128 literal bytes are n - 1 and the bytes."""
    out = bytearray()
    i, n = 0, len(channel)
    while i < n:
        run = 1
        while i + run < n and run < 130 and channel[i + run] == channel[i]:
            run += 1
        if run >= 3:
            out += bytes([0x80 + run - 3, channel[i]])
            i += run
            continue
        j = i
        while j < n and j - i < 128:
            if j + 2 < n and channel[j] == channel[j + 1] == channel[j + 2]:
                break
            j += 1
        out += bytes([j - i - 1]) + channel[i:j]
        i = j
    return bytes(out)


def element(tag, data):
    return tag + struct.pack(">I", 8 + len(data)) + data


def main():
    body = b""
    for size, rgb_tag, mask_tag in SIZES:
        im = Image.open(os.path.join(ROOT, "img", f"{size}x{size}x32.png")).convert("RGBA")
        assert im.size == (size, size)
        px = im.tobytes()
        r, g, b, a = (px[k::4] for k in range(4))
        rgb = rle(r) + rle(g) + rle(b)
        if rgb_tag == b"it32":
            rgb = bytes(4) + rgb  # it32 starts with four zero bytes
        body += element(rgb_tag, rgb) + element(mask_tag, a)
    icns = element(b"icns", body)
    lines = ["/* Generated by tools/mkicns.py from img/*.png: the Mac OS X icon family",
             "   of the Carbon build's application icon (ICN# 128). */",
             "data 'icns' (128) {"]
    for i in range(0, len(icns), 32):
        lines.append('    $"' + icns[i:i + 32].hex().upper() + '"')
    lines.append("};")
    open(sys.argv[1], "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
